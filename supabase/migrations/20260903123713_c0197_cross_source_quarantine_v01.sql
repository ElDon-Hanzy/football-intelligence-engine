create table if not exists public.research_c0197_cross_source_match_audits (
  id bigint generated by default as identity primary key,
  change_id text not null default 'C0197',
  audit_definition_version text not null,
  season text not null,
  football_data_capture_id bigint not null references public.research_c0197_long_history_captures(id),
  football_data_source_match_id text not null,
  fpl_core_source_match_id text not null,
  fpl_core_source_commit_sha text,
  gameweek integer,
  score_exact boolean not null,
  core_equals_football_data_halftime boolean not null,
  shot_abs_delta numeric not null,
  sot_abs_delta numeric not null,
  score_status text not null,
  stat_status text not null,
  goal_residual_eligible boolean not null,
  process_feature_eligible boolean not null,
  overall_rich_feature_eligible boolean not null,
  audit_evidence jsonb not null,
  research_only boolean not null default true,
  model_effect_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  unique (football_data_capture_id, fpl_core_source_match_id, audit_definition_version),
  check (research_only = true),
  check (model_effect_enabled = false)
);

alter table public.research_c0197_cross_source_match_audits enable row level security;
revoke all on public.research_c0197_cross_source_match_audits from anon, authenticated;

