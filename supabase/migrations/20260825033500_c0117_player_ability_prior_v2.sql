      (17,'newcastle-united','Newcastle'),(18,'nottingham-forest','Nott''m Forest'),
      (19,'tottenham-hotspur','Tottenham'),(20,'sunderland','Sunderland')
    ) v(team_id,source_slug,elo_name)
  ), opponent_alias as materialized (
    select * from (values
      ('afc-bournemouth','Bournemouth'),('arsenal','Arsenal'),('aston-villa','Aston Villa'),('brentford','Brentford'),
      ('brighton-hove-albion','Brighton'),('burnley','Burnley'),('chelsea','Chelsea'),('crystal-palace','Crystal Palace'),
