create or replace function private.c0204_projection_coverage_rows_v01(p_gameweek integer, p_as_of timestamptz default clock_timestamp())
returns table(
  player_id bigint,
  web_name text,
  player_position text,
  team_id bigint,
  fpl_player_id integer,
  player_status text,
  has_current_state boolean,
  has_baseline_prediction boolean,
  latest_eligibility_status text,
  coverage_status text,
  reason_code text
)
language sql stable security definer set search_path=private,public,pg_temp as $$
with active_model as (
  select id from public.model_versions where is_active=true order by id desc limit 1
), target_players as (
  select p.*
  from public.players p
  where p.fpl_player_id is not null
    and exists (
      select 1 from public.matches m
      where m.source='fpl' and m.gameweek=p_gameweek
        and (m.home_team_id=p.team_id or m.away_team_id=p.team_id)
    )
), facts as (
  select p.id,p.web_name,p.position,p.team_id,p.fpl_player_id,p.status,
    exists(select 1 from public.player_state ps where ps.player_id=p.id and ps.as_of<=p_as_of) as has_state,
    exists(select 1 from public.model_predictions mp, active_model am where mp.player_id=p.id and mp.model_version_id=am.id and mp.prediction_run_id is null and mp.generated_at<p_as_of) as has_baseline,
    ev.eligibility_status as ev_status,
    ev.reason_code as ev_reason
  from target_players p
  left join lateral (
    select e.eligibility_status,e.reason_code
    from public.fpl_projection_eligibility_events e
    where e.player_id=p.id and e.event_at<=p_as_of
    order by e.event_at desc,e.id desc limit 1
  ) ev on true
)
select id,web_name,position,team_id,fpl_player_id,status,
  has_state,has_baseline,ev_status,
  case when has_state and has_baseline then 'PROJECTABLE'
       when ev_status='EXCLUDED' then 'EXCLUDED_GOVERNED'
       else 'UNGOVERNED_MISSING' end,
  case when has_state and has_baseline then 'OK'
       when ev_status='EXCLUDED' then ev_reason
       when not has_state and not has_baseline then 'MISSING_STATE_AND_BASELINE'
       when not has_state then 'MISSING_CURRENT_STATE'
       else 'MISSING_BASELINE_PREDICTION' end
from facts;
$$;

create or replace function private.c0204_projection_coverage_summary_v01(p_gameweek integer, p_as_of timestamptz default clock_timestamp())
returns jsonb language sql stable security definer set search_path=private,public,pg_temp as $$
with r as (select * from private.c0204_projection_coverage_rows_v01(p_gameweek,p_as_of))
select jsonb_build_object(
  'change_id','C0204',
  'gameweek',p_gameweek,
  'as_of',p_as_of,
  'total_fpl_players',count(*),
  'projectable_count',count(*) filter(where coverage_status='PROJECTABLE'),
  'governed_excluded_count',count(*) filter(where coverage_status='EXCLUDED_GOVERNED'),
  'ungoverned_missing_count',count(*) filter(where coverage_status='UNGOVERNED_MISSING'),
  'missing_data_is_not_zero',true,
  'excluded',coalesce(jsonb_agg(jsonb_build_object('player_id',player_id,'name',web_name,'position',player_position,'status',player_status,'reason',reason_code) order by player_id) filter(where coverage_status<>'PROJECTABLE'),'[]'::jsonb)
) from r;
$$;

