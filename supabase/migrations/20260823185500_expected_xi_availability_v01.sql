create table if not exists public.player_fixture_availability_observations (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id),
  gameweek integer not null,
  team_id bigint not null references public.teams(id),
  opponent_team_id bigint not null references public.teams(id),
  player_id bigint not null references public.players(id),
  kickoff_time timestamptz not null,
  captured_at timestamptz not null default now(),
  source text not null default 'official_fpl',
  source_updated_at timestamptz,
  fpl_status_code text,
  availability_status text not null check (availability_status in ('AVAILABLE','DOUBTFUL','INJURED','SUSPENDED','UNAVAILABLE','UNKNOWN')),
  chance_of_playing numeric check (chance_of_playing is null or (chance_of_playing >= 0 and chance_of_playing <= 1)),
  news text,
  player_state_as_of timestamptz,
  base_start_probability numeric check (base_start_probability is null or (base_start_probability >= 0 and base_start_probability <= 1)),
  base_expected_minutes numeric check (base_expected_minutes is null or base_expected_minutes >= 0),
  xi_score numeric check (xi_score is null or xi_score >= 0),
  expected_xi boolean not null default false,
  expected_xi_formation text,
  xi_rank_within_position integer,
  confidence numeric check (confidence is null or (confidence >= 0 and confidence <= 1)),
  observation_hash text not null,
  evidence jsonb not null default '{}'::jsonb,
  model_effect_enabled boolean not null default false,
  constraint player_fixture_availability_obs_unique unique (match_id, player_id, observation_hash),
  constraint player_fixture_availability_preko_check check (captured_at < kickoff_time),
  constraint player_fixture_availability_model_effect_check check (model_effect_enabled = false)
);

create index if not exists idx_pfao_match_capture on public.player_fixture_availability_observations(match_id,captured_at desc);
create index if not exists idx_pfao_player_capture on public.player_fixture_availability_observations(player_id,captured_at desc);
create index if not exists idx_pfao_team_match on public.player_fixture_availability_observations(team_id,match_id,captured_at desc);

