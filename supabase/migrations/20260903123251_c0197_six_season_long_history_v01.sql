create or replace function private.c0197_safe_int_v01(p_value text)
returns integer
language sql
immutable
set search_path = pg_catalog
as $$
  select case when btrim(coalesce(p_value,'')) ~ '^-?[0-9]+$' then btrim(p_value)::integer else null end;
$$;

create or replace function private.c0197_safe_numeric_v01(p_value text)
returns numeric
language sql
immutable
set search_path = pg_catalog
as $$
  select case when btrim(coalesce(p_value,'')) ~ '^-?[0-9]+([.][0-9]+)?$' then btrim(p_value)::numeric else null end;
$$;

