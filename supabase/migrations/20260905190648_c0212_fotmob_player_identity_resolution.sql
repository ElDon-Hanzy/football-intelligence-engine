create table if not exists public.fotmob_player_identity_observations (
  id bigint generated by default as identity primary key,
  change_id text not null default 'C0212',
  source_fotmob_player_id bigint not null,
  player_id bigint not null references public.players(id),
  mapping_method text not null,
  confidence numeric not null check (confidence between 0 and 1),
  evidence jsonb not null default '{}'::jsonb,
  observed_at timestamptz not null default now(),
  observation_hash text not null unique
);
create index if not exists fotmob_player_identity_source_idx on public.fotmob_player_identity_observations(source_fotmob_player_id, observed_at desc, id desc);
alter table public.fotmob_player_identity_observations enable row level security;
revoke all on public.fotmob_player_identity_observations from anon, authenticated;
grant select, insert on public.fotmob_player_identity_observations to service_role;
grant usage, select on sequence public.fotmob_player_identity_observations_id_seq to service_role;

drop trigger if exists trg_c0212_fotmob_identity_append_only on public.fotmob_player_identity_observations;
create trigger trg_c0212_fotmob_identity_append_only
before update or delete on public.fotmob_player_identity_observations
for each row execute function private.block_c0212_realized_role_mutation();

