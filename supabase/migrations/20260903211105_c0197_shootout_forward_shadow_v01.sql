create or replace function private.c0197_capture_shootout_forward_v01(p_gameweek integer, p_as_of timestamptz default clock_timestamp())
returns jsonb language plpgsql set search_path=public,private,pg_temp as $$
declare
  v_inserted integer := 0;
  v_run_key constant text := 'C0197_SHOOTOUT_FORWARD_20260904_V01';
begin
  with fixtures as (
    select m.id match_id,m.gameweek,m.kickoff_time,m.home_team_id,m.away_team_id,ht.name home_team,at.name away_team
    from public.matches m join public.teams ht on ht.id=m.home_team_id join public.teams at on at.id=m.away_team_id
    where m.gameweek=p_gameweek and not m.finished and m.kickoff_time>p_as_of
  ), sides as (
    select f.*,f.home_team_id team_id,'home'::text side from fixtures f
    union all
    select f.*,f.away_team_id,'away'::text from fixtures f
  ), base_hist as (
    select s.match_id,s.side,s.team_id,
      count(h.*)::integer hist_n,
      (coalesce(sum(h.shots_on_target_for),0) + (10-count(h.*))*4.403350)/10.0 eff_sot,
      (coalesce(sum(h.goals_for),0) + (10-count(h.*))*1.389655)/10.0 eff_gf,
      (coalesce(sum(case when h.goals_for>0 and h.goals_against>0 then 1.0 else 0.0 end),0) + (10-count(h.*))*0.498325)/10.0 eff_btts
    from sides s
    left join lateral (
      select e.* from public.research_c0197_team_match_evidence e
      where e.team_id=s.team_id
        and e.season in ('2025-2026','2026-2027')
        and e.fixture_kickoff < least(s.kickoff_time,p_as_of)
      order by e.fixture_kickoff desc,e.gameweek desc,e.id desc
      limit 10
    ) h on true
    group by s.match_id,s.side,s.team_id
  ), shot_quality as (
    select q.season,q.gameweek,q.source_match_id,q.team_id,q.venue,e.fixture_kickoff
    from private.c0197_shot_side_quality_v01 q
    join public.research_c0197_team_match_evidence e
      on e.season=q.season and e.source_match_id=q.source_match_id and e.team_id=q.team_id and e.venue=q.venue
    where q.season in ('2025-2026','2026-2027')
      and q.esot_training_eligible
      and e.fixture_kickoff < p_as_of
  ), player_shot as (
    select q.season,q.gameweek,q.source_match_id,q.team_id,q.venue,q.fixture_kickoff,s.source_player_id,
      sum(coalesce(s.xg,0)) player_xg,
      bool_or(lower(coalesce(s.outcome,'')) in ('goal','save')) has_sot
    from shot_quality q
    join public.research_c0197_shot_events s
      on s.season=q.season and s.source_match_id=q.source_match_id and s.is_home=(q.venue='home')
    group by q.season,q.gameweek,q.source_match_id,q.team_id,q.venue,q.fixture_kickoff,s.source_player_id
  ), breadth_side as (
    select season,gameweek,source_match_id,team_id,venue,fixture_kickoff,
      count(*) filter(where source_player_id is not null and has_sot)::numeric sot_players,
      greatest(0,sum(player_xg)-coalesce((array_agg(player_xg order by player_xg desc))[1],0)-coalesce((array_agg(player_xg order by player_xg desc))[2],0))::numeric xg_breadth,
      sum(case when source_player_id is null then player_xg else 0 end)::numeric unknown_player_xg
    from player_shot
    group by season,gameweek,source_match_id,team_id,venue,fixture_kickoff
  ), breadth_hist as (
    select s.match_id,s.side,s.team_id,
      count(h.*)::integer hist_n,
      (coalesce(sum(h.sot_players),0)+(10-count(h.*))*3.420807)/10.0 eff_sot_players,
      (coalesce(sum(h.xg_breadth),0)+(10-count(h.*))*0.537464)/10.0 eff_xg_breadth
    from sides s
    left join lateral (
      select b.* from breadth_side b
      where b.team_id=s.team_id and b.fixture_kickoff < least(s.kickoff_time,p_as_of) and b.unknown_player_xg<=0.000001
      order by b.fixture_kickoff desc,b.gameweek desc,b.source_match_id desc
      limit 10
    ) h on true
    group by s.match_id,s.side,s.team_id
  ), opening_quotes as (
    select * from (
      select o.*,
        row_number() over(partition by o.match_id,o.provider,o.bookmaker,o.selection_key order by o.captured_at asc,o.source_timestamp asc,o.id asc) rn
      from public.odds_market_selections o
      join fixtures f on f.match_id=o.match_id
      where o.market_key='h2h' and o.selection_key in ('home','draw','away')
        and o.decimal_odds>1 and o.captured_at<=p_as_of
    ) x where rn=1
  ), market_books as (
    select match_id,provider,bookmaker,
      max(decimal_odds) filter(where selection_key='home') oh,
      max(decimal_odds) filter(where selection_key='draw') od,
      max(decimal_odds) filter(where selection_key='away') oa
    from opening_quotes group by match_id,provider,bookmaker
  ), market_norm as (
    select match_id,provider,bookmaker,
      (1/oh)/((1/oh)+(1/od)+(1/oa)) ph,
      (1/od)/((1/oh)+(1/od)+(1/oa)) pd,
      (1/oa)/((1/oh)+(1/od)+(1/oa)) pa
    from market_books where oh is not null and od is not null and oa is not null
  ), market as (
    select match_id,count(*)::integer bookmakers,avg(ph) ph,avg(pd) pd,avg(pa) pa
    from market_norm group by match_id
  ), features as (
    select f.*,coalesce(m.bookmakers,0) market_bookmakers,m.ph,m.pd,m.pa,
      greatest(m.ph,m.pa) favorite_prob,1-greatest(m.ph,m.pa) inverse_favorite_prob,
      hb.hist_n home_history_n,ab.hist_n away_history_n,hb.eff_sot home_sot,ab.eff_sot away_sot,
      least(hb.eff_sot,ab.eff_sot) min_sot,hb.eff_gf home_gf,ab.eff_gf away_gf,least(hb.eff_gf,ab.eff_gf) min_gf,
      hb.eff_btts home_btts_rate,ab.eff_btts away_btts_rate,(hb.eff_btts+ab.eff_btts)/2 btts_rate,
      hbr.hist_n home_breadth_n,abr.hist_n away_breadth_n,hbr.eff_sot_players home_sot_players,abr.eff_sot_players away_sot_players,
      least(hbr.eff_sot_players,abr.eff_sot_players) min_sot_players,
      hbr.eff_xg_breadth home_xg_breadth,abr.eff_xg_breadth away_xg_breadth,
      least(hbr.eff_xg_breadth,abr.eff_xg_breadth) min_xg_breadth
    from fixtures f
    join base_hist hb on hb.match_id=f.match_id and hb.side='home'
    join base_hist ab on ab.match_id=f.match_id and ab.side='away'
    join breadth_hist hbr on hbr.match_id=f.match_id and hbr.side='home'
    join breadth_hist abr on abr.match_id=f.match_id and abr.side='away'
    left join market m on m.match_id=f.match_id
  ), scored as (
    select *,
      (min_sot-3.767980)/0.807958 z_min_sot,
      (min_gf-1.063636)/0.391222 z_min_gf,
      (btts_rate-0.497121)/0.110584 z_btts,
      case when inverse_favorite_prob is null then null else (inverse_favorite_prob-0.462185)/0.132885 end z_inverse_favorite,
      (min_sot_players-3.105051)/0.447752 z_min_sot_players,
      (min_xg_breadth-0.456922)/0.105019 z_min_xg_breadth,
      least(home_history_n,away_history_n)/10.0 base_history_coverage,
      least(home_breadth_n,away_breadth_n)/10.0 breadth_history_coverage
    from features
  ), final_score as (
    select *,
      case when z_inverse_favorite is null then null else (z_min_sot+z_min_gf+z_btts+z_inverse_favorite)/4.0 end base_score_v01,
      (z_min_sot_players+z_min_xg_breadth)/2.0 breadth_score_v01,
      case when z_inverse_favorite is null then null else (z_min_sot+z_min_gf+z_btts+z_inverse_favorite+z_min_sot_players+z_min_xg_breadth)/6.0 end combined_score_v02
    from scored
  ), ranked as (
    select *,
      case when base_score_v01 is null then null else rank() over(order by base_score_v01 desc nulls last)::integer end base_rank,
      case when combined_score_v02 is null then null else rank() over(order by combined_score_v02 desc nulls last)::integer end combined_rank,
      case when least(home_history_n,away_history_n)>=10 and least(home_breadth_n,away_breadth_n)>=8 and market_bookmakers>=5 then 'HIGH'
           when least(home_history_n,away_history_n)>=8 and least(home_breadth_n,away_breadth_n)>=5 and market_bookmakers>=3 then 'MEDIUM'
           else 'LOW' end confidence
    from final_score
  ), ins as (
    insert into public.research_c0197_shootout_forward_snapshots(
      run_key,observation_hash,snapshot_as_of,match_id,gameweek,kickoff_time,home_team_id,away_team_id,home_team,away_team,
      market_bookmakers,market_home_prob,market_draw_prob,market_away_prob,favorite_prob,inverse_favorite_prob,
      home_history_n,away_history_n,home_sot,away_sot,min_sot,home_gf,away_gf,min_gf,home_btts_rate,away_btts_rate,btts_rate,
      z_min_sot,z_min_gf,z_btts,z_inverse_favorite,base_score_v01,
      home_breadth_n,away_breadth_n,home_sot_players,away_sot_players,min_sot_players,home_xg_breadth,away_xg_breadth,min_xg_breadth,
      z_min_sot_players,z_min_xg_breadth,breadth_score_v01,combined_score_v02,base_rank,combined_rank,base_history_coverage,breadth_history_coverage,confidence,evidence
    )
    select v_run_key,
      md5(concat_ws('|',match_id,round(coalesce(base_score_v01,-99)::numeric,8),round(coalesce(combined_score_v02,-99)::numeric,8),home_history_n,away_history_n,home_breadth_n,away_breadth_n,market_bookmakers)),
      p_as_of,match_id,gameweek,kickoff_time,home_team_id,away_team_id,home_team,away_team,
      market_bookmakers,ph,pd,pa,favorite_prob,inverse_favorite_prob,
      home_history_n,away_history_n,home_sot,away_sot,min_sot,home_gf,away_gf,min_gf,home_btts_rate,away_btts_rate,btts_rate,
      z_min_sot,z_min_gf,z_btts,z_inverse_favorite,base_score_v01,
      home_breadth_n,away_breadth_n,home_sot_players,away_sot_players,min_sot_players,home_xg_breadth,away_xg_breadth,min_xg_breadth,
      z_min_sot_players,z_min_xg_breadth,breadth_score_v01,combined_score_v02,base_rank,combined_rank,base_history_coverage,breadth_history_coverage,confidence,
      jsonb_build_object('market_policy','earliest captured h2h quote per bookmaker before snapshot','history_policy','2025/26 + 2026/27 EPL evidence only; shrink missing slots to fixed prior','breadth_quality','C0197 shot reconciliation eligible sides only')
    from ranked
    on conflict(run_key,match_id,observation_hash) do nothing
    returning id
  ) select count(*) into v_inserted from ins;

  return jsonb_build_object(
    'run_key',v_run_key,
    'gameweek',p_gameweek,
    'snapshot_as_of',p_as_of,
    'inserted',v_inserted,
    'model_effect_enabled',false,
    'top_base',(select jsonb_build_object('match',home_team||' vs '||away_team,'score',round(base_score_v01,4),'rank',base_rank,'confidence',confidence) from public.research_c0197_shootout_forward_snapshots where run_key=v_run_key and gameweek=p_gameweek and snapshot_as_of<=p_as_of order by snapshot_as_of desc,base_rank asc limit 1),
    'top_combined',(select jsonb_build_object('match',home_team||' vs '||away_team,'score',round(combined_score_v02,4),'rank',combined_rank,'confidence',confidence) from public.research_c0197_shootout_forward_snapshots where run_key=v_run_key and gameweek=p_gameweek and snapshot_as_of<=p_as_of order by snapshot_as_of desc,combined_rank asc limit 1)
  );
end $$;
