  'change_id','C0197',
  'run_key','C0197_SHOOTOUT_FORWARD_20260904_V01',
  'runs',(select count(*) from public.research_c0197_shootout_forward_runs),
  'scalers',(select count(*) from public.research_c0197_shootout_forward_scalers),
  'snapshots',(select count(*) from public.research_c0197_shootout_forward_snapshots),
  'market_checks',(select count(*) from public.research_c0197_shootout_forward_market_checks),
  'evaluations',(select count(*) from public.research_c0197_shootout_forward_evaluations),
  'gameweeks',(select coalesce(jsonb_agg(distinct gameweek order by gameweek),'[]'::jsonb) from public.research_c0197_shootout_forward_snapshots),
  'model_effect_enabled',false
); $$;
