create table if not exists public.research_c0202_directional_matchup_snapshots (
  id bigint generated by default as identity primary key,
  run_key text not null references public.research_c0202_validation_runs(run_key),
  evidence_cutoff timestamptz not null,
  gameweek integer not null,
  match_id bigint not null references public.matches(id),
  kickoff_time timestamptz not null,
  attacking_team_id bigint not null references public.teams(id),
  defending_team_id bigint not null references public.teams(id),
  attacker_player_id bigint not null references public.players(id),
  attacker_role text not null,
  attacker_side text not null check (attacker_side in ('ATT_LEFT','ATT_RIGHT')),
  attacker_side_confidence_band text not null check (attacker_side_confidence_band in ('HIGH','MEDIUM')),
  attacker_side_empirical_accuracy numeric not null check (attacker_side_empirical_accuracy between 0 and 1),
  faced_defensive_side text not null check (faced_defensive_side in ('DEF_LEFT','DEF_RIGHT')),
  expected_defender_player_id bigint references public.players(id),
  expected_defender_role text,
  defender_side_confidence_band text check (defender_side_confidence_band is null or defender_side_confidence_band in ('HIGH','MEDIUM')),
  defender_side_empirical_accuracy numeric check (defender_side_empirical_accuracy is null or defender_side_empirical_accuracy between 0 and 1),
  defender_pair_status text not null check (defender_pair_status in ('PAIRED_EXACT_SIDE','UNRESOLVED_EXACT_OPPONENT')),
  mapping_quality text not null check (mapping_quality in ('HIGH','MEDIUM','UNRESOLVED')),
  attacker_role_captured_at timestamptz not null,
  defender_role_captured_at timestamptz,
  wide_context_score numeric,
  wide_context_direction text,
  wide_context_confidence numeric check (wide_context_confidence is null or wide_context_confidence between 0 and 1),
  wide_context_captured_at timestamptz,
  defending_team_personnel_score numeric,
  defending_team_personnel_direction text,
  defending_team_personnel_confidence numeric check (defending_team_personnel_confidence is null or defending_team_personnel_confidence between 0 and 1),
  defending_team_personnel_captured_at timestamptz,
  effect_direction text not null default 'UNRESOLVED' check (effect_direction in ('ATTACK_ADVANTAGE','DEFENSIVE_ADVANTAGE','BALANCED','UNRESOLVED')),
  effect_magnitude numeric,
  effect_confidence numeric check (effect_confidence is null or effect_confidence between 0 and 1),
  evidence jsonb not null default '{}'::jsonb,
  research_only boolean not null default true check (research_only),
  model_effect_enabled boolean not null default false check (not model_effect_enabled),
  created_at timestamptz not null default clock_timestamp(),
  unique(run_key,match_id,attacker_player_id),
  check (attacker_role_captured_at <= evidence_cutoff),
  check (defender_role_captured_at is null or defender_role_captured_at <= evidence_cutoff),
  check (wide_context_captured_at is null or wide_context_captured_at <= evidence_cutoff),
  check (defending_team_personnel_captured_at is null or defending_team_personnel_captured_at <= evidence_cutoff),
  check ((effect_direction='UNRESOLVED' and effect_magnitude is null and effect_confidence is null) or effect_direction<>'UNRESOLVED')
);

