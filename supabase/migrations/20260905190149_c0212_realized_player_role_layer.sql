create table if not exists public.realized_player_role_observations (
  id bigint generated by default as identity primary key,
  change_id text not null default 'C0212',
  source_key text not null default 'fotmob_match_details',
  source_url text not null,
  source_fotmob_match_id bigint not null,
  source_fotmob_player_id bigint not null,
  match_id bigint not null references public.matches(id),
  gameweek integer not null check (gameweek between 1 and 38),
  kickoff_time timestamptz not null,
  team_id bigint not null references public.teams(id),
  player_id bigint references public.players(id),
  player_name text not null,
  fpl_position text,
  usual_playing_position_id integer,
  formation text,
  is_starting boolean not null default true,
  position_id integer,
  layout_x numeric,
  layout_y numeric,
  tactical_band text,
  width_band text,
  realized_role text,
  role_confidence numeric check (role_confidence is null or (role_confidence >= 0 and role_confidence <= 1)),
  mapping_status text not null,
  source_payload jsonb not null default '{}'::jsonb,
  captured_at timestamptz not null default now(),
  evidence_cutoff timestamptz not null default now(),
  observation_hash text not null unique,
  production_role_enabled boolean not null default true,
  model_effect_enabled boolean not null default false,
  constraint realized_role_xy_pair check ((layout_x is null) = (layout_y is null))
);

create index if not exists realized_player_role_player_recent_idx
  on public.realized_player_role_observations(player_id, kickoff_time desc, id desc)
  where player_id is not null and is_starting;
create index if not exists realized_player_role_match_idx
  on public.realized_player_role_observations(match_id, team_id);
create index if not exists realized_player_role_source_player_idx
  on public.realized_player_role_observations(source_fotmob_player_id, kickoff_time desc);

