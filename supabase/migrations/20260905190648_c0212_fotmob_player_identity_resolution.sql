create or replace view public.current_fotmob_player_identities
with (security_invoker = true)
as
select distinct on (source_fotmob_player_id)
  source_fotmob_player_id,player_id,mapping_method,confidence,evidence,observed_at,observation_hash
from public.fotmob_player_identity_observations
order by source_fotmob_player_id,observed_at desc,id desc;
revoke all on public.current_fotmob_player_identities from anon, authenticated;
grant select on public.current_fotmob_player_identities to service_role;

create or replace view public.current_realized_player_roles
with (security_invoker = true)
as
with resolved as (
  select r.*,
         coalesce(r.player_id,i.player_id) as resolved_player_id,
         case when r.player_id is not null then r.mapping_status else i.mapping_method end as resolved_mapping_method
  from public.realized_player_role_observations r
  left join public.current_fotmob_player_identities i on i.source_fotmob_player_id=r.source_fotmob_player_id
), ranked as (
  select r.*,
         row_number() over(partition by r.resolved_player_id order by r.kickoff_time desc, r.id desc) as rn
  from resolved r
  where r.resolved_player_id is not null
    and r.is_starting
    and r.realized_role is not null
    and r.production_role_enabled
), recent as (
  select * from ranked where rn <= 3
), latest as (
  select * from ranked where rn = 1
), agg as (
  select resolved_player_id,
         count(*)::integer as recent_role_samples,
         count(*) filter(where realized_role = (select l.realized_role from latest l where l.resolved_player_id=recent.resolved_player_id))::integer as latest_role_matches_l3
  from recent
  group by resolved_player_id
)
select l.resolved_player_id as player_id,
       l.realized_role as current_role,
       l.realized_role as latest_realized_role,
       l.tactical_band as latest_tactical_band,
       l.width_band as latest_width_band,
       l.formation as latest_formation,
       l.role_confidence as latest_role_confidence,
       a.recent_role_samples,
       a.latest_role_matches_l3,
       case when a.recent_role_samples > 0 then a.latest_role_matches_l3::numeric/a.recent_role_samples else null end as role_stability,
       l.kickoff_time as latest_role_match_kickoff,
       l.evidence_cutoff as latest_known_at,
       l.observation_hash as latest_observation_hash,
       l.source_key,
       l.source_url,
       l.source_fotmob_player_id,
       coalesce(l.fpl_position,p.position) as fpl_position,
       l.usual_playing_position_id,
       l.resolved_mapping_method as mapping_method
from latest l
join agg a using(resolved_player_id)
join public.players p on p.id=l.resolved_player_id;

revoke all on public.current_realized_player_roles from anon, authenticated;
grant select on public.current_realized_player_roles to service_role;
