-- C0128 — Context-specific venue effect benchmark v0.1
-- Retrospective research only. Does not modify W0001/A0005, E0007 or W0002.
create table if not exists public.venue_context_benchmarks (
  id bigint generated by default as identity primary key,
  change_id text not null,
  experiment_key text not null,
  evaluation_scope text not null,
  window_label text not null,
  variant text not null,
  sample_n integer not null,
  mae numeric not null,
  rmse numeric not null,
  chronology_safe boolean not null default true,
  retrospective_only boolean not null default true,
  model_effect_enabled boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  unique(experiment_key,evaluation_scope,window_label,variant)
);
alter table public.venue_context_benchmarks enable row level security;
revoke all on public.venue_context_benchmarks from anon, authenticated;
create or replace function private.block_venue_context_benchmark_mutation_v01() returns trigger language plpgsql as $$ begin raise exception 'venue_context_benchmarks is append-only'; end $$;
drop trigger if exists venue_context_benchmarks_append_only on public.venue_context_benchmarks;
create trigger venue_context_benchmarks_append_only before update or delete on public.venue_context_benchmarks for each row execute function private.block_venue_context_benchmark_mutation_v01();
create or replace function private.venue_context_benchmark_status_v01() returns jsonb language sql security invoker set search_path=public,private as $$
 select jsonb_build_object(
   'experiment_key','E0011',
   'rows',count(*),
   'historical_windows',count(distinct window_label) filter(where evaluation_scope='HISTORICAL_CHRONOLOGICAL'),
   'gw1_rows',count(*) filter(where evaluation_scope='RETROSPECTIVE_GW1_DIAGNOSTIC'),
   'model_effect_enabled',coalesce(bool_or(model_effect_enabled),false),
   'decision','REJECT_NO_CROSS_WINDOW_STABILITY'
 ) from public.venue_context_benchmarks where experiment_key='E0011';
$$;
