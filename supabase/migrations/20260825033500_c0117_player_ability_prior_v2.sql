-- C0117 — Player ability prior v2 evidence expansion
-- Research only. Does not alter A0005 or any frozen prediction.

create table if not exists public.player_ability_prior_v2_observations (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id),
  team_id bigint not null references public.teams(id),
  season text not null,
  position text not null,
  observed_at timestamptz not null default clock_timestamp(),
  season_minutes integer not null,
  base_attack_quality_percentile numeric,
  base_defence_quality_percentile numeric,
  base_overall_quality_percentile numeric,
  event_matches integer not null default 0,
  team_continuity_ratio numeric,
  opponent_elo_coverage numeric,
  average_opponent_pre_match_elo numeric,
  attack_per90_event_raw numeric,
  defence_per90_event_raw numeric,
  attack_per90_opponent_adjusted numeric,
  defence_per90_opponent_adjusted numeric,
  attack_per90_v2_shrunk numeric,
  defence_per90_v2_shrunk numeric,
  attack_quality_percentile_v2 numeric,
  defence_quality_percentile_v2 numeric,
  overall_quality_percentile_v2 numeric,
  confidence numeric not null,
  opponent_adjustment_applied boolean not null default false,
  method text not null,
  evidence jsonb not null default '{}'::jsonb,
  actual_data_used boolean not null default false,
  model_effect_enabled boolean not null default false,
  constraint player_ability_prior_v2_unique unique(player_id,season,method),
  constraint player_ability_prior_v2_flags_check check (actual_data_used=false and model_effect_enabled=false)
);

alter table public.player_ability_prior_v2_observations enable row level security;
revoke all on public.player_ability_prior_v2_observations from anon, authenticated;

create index if not exists player_ability_prior_v2_player_idx
  on public.player_ability_prior_v2_observations(player_id,season);
create index if not exists player_ability_prior_v2_position_idx
  on public.player_ability_prior_v2_observations(position,season);

