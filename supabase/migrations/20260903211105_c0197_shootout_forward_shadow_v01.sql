create or replace function private.c0197_evaluate_shootout_forward_v01(p_gameweek integer)
returns jsonb language plpgsql set search_path=public,private,pg_temp as $$
declare v_inserted integer := 0; v_run_key constant text := 'C0197_SHOOTOUT_FORWARD_20260904_V01';
begin
  with first_snap as (
    select distinct on (s.match_id) s.* from public.research_c0197_shootout_forward_snapshots s
    where s.run_key=v_run_key and s.gameweek=p_gameweek
    order by s.match_id,s.snapshot_as_of asc,s.id asc
  ), ins as (
    insert into public.research_c0197_shootout_forward_evaluations(run_key,snapshot_id,match_id,gameweek,actual_home_goals,actual_away_goals,actual_total_goals,actual_shootout,actual_demolition,base_top10,combined_top10)
    select v_run_key,s.id,m.id,m.gameweek,m.home_score,m.away_score,m.home_score+m.away_score,
      (m.home_score+m.away_score>=6 and m.home_score>=2 and m.away_score>=2),
      (m.home_score+m.away_score>=6 and least(m.home_score,m.away_score)<=1),
      s.base_rank<=greatest(1,ceil((select count(*) from first_snap)*0.10)::integer),
      s.combined_rank<=greatest(1,ceil((select count(*) from first_snap)*0.10)::integer)
    from first_snap s join public.matches m on m.id=s.match_id
    where m.finished and m.home_score is not null and m.away_score is not null
    on conflict(run_key,snapshot_id) do nothing returning id
  ) select count(*) into v_inserted from ins;
  return jsonb_build_object('run_key',v_run_key,'gameweek',p_gameweek,'inserted',v_inserted,'model_effect_enabled',false);
