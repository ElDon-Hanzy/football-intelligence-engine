create or replace function private.generate_upcoming_fpl_snapshot_v01(p_gameweek integer default null, p_force boolean default false)
returns jsonb
language plpgsql security definer set search_path=private,public,pg_temp as $$
declare
  v_now timestamptz := clock_timestamp();
  v_gw integer;
  v_cov jsonb;
  v_res jsonb;
  v_run_id bigint;
begin
  if p_gameweek is null then
    select x.gameweek into v_gw
    from (
      select m.gameweek,min(m.kickoff_time)-interval '90 minutes' deadline_at
      from public.matches m where m.source='fpl' and m.gameweek between 1 and 38
      group by m.gameweek
    ) x
    where x.deadline_at>v_now order by x.gameweek limit 1;
  else
    v_gw:=p_gameweek;
  end if;
  if v_gw is null then
    return jsonb_build_object('ok',false,'status','NO_FUTURE_GAMEWEEK','change_id','C0204');
  end if;

  v_cov:=private.c0204_projection_coverage_summary_v01(v_gw,v_now);
  if coalesce((v_cov->>'ungoverned_missing_count')::integer,0)>0 then
    insert into public.fpl_projection_coverage_audits(prediction_run_id,gameweek,captured_at,projectable_count,governed_excluded_count,ungoverned_missing_count,total_fpl_players,coverage)
    values(null,v_gw,v_now,(v_cov->>'projectable_count')::integer,(v_cov->>'governed_excluded_count')::integer,(v_cov->>'ungoverned_missing_count')::integer,(v_cov->>'total_fpl_players')::integer,v_cov);
    return jsonb_build_object('ok',false,'status','C0204_PROJECTION_COVERAGE_BLOCKED','gameweek',v_gw,'projection_coverage',v_cov,'historical_forecasts_rewritten',false);
  end if;

  v_res:=private.generate_upcoming_fpl_snapshot_c0160_legacy_v01(v_gw,p_force);
  if v_res ? 'run_id' then v_run_id:=(v_res->>'run_id')::bigint; end if;
  insert into public.fpl_projection_coverage_audits(prediction_run_id,gameweek,captured_at,projectable_count,governed_excluded_count,ungoverned_missing_count,total_fpl_players,coverage)
  values(v_run_id,v_gw,v_now,(v_cov->>'projectable_count')::integer,(v_cov->>'governed_excluded_count')::integer,(v_cov->>'ungoverned_missing_count')::integer,(v_cov->>'total_fpl_players')::integer,v_cov);
  return v_res || jsonb_build_object('change_id','C0204','projection_coverage',v_cov,'historical_forecasts_rewritten',false);
end;$$;

create or replace function private.c0204_projection_coverage_status_v01(p_gameweek integer default null)
returns jsonb language plpgsql stable security definer set search_path=private,public,pg_temp as $$
declare v_gw integer; v_s jsonb;
begin
  if p_gameweek is null then
    select x.gameweek into v_gw from (select m.gameweek,min(m.kickoff_time)-interval '90 minutes' deadline_at from public.matches m where m.source='fpl' and m.gameweek between 1 and 38 group by m.gameweek) x where x.deadline_at>clock_timestamp() order by x.gameweek limit 1;
  else v_gw:=p_gameweek; end if;
  if v_gw is null then return jsonb_build_object('change_id','C0204','status','NO_FUTURE_GAMEWEEK'); end if;
  v_s:=private.c0204_projection_coverage_summary_v01(v_gw,clock_timestamp());
  return v_s || jsonb_build_object('latest_audit',(select to_jsonb(a) from public.fpl_projection_coverage_audits a where a.gameweek=v_gw order by a.captured_at desc,a.id desc limit 1));
end;$$;