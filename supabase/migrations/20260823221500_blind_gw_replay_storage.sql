create index if not exists blind_replay_signals_opponent_fk_idx on public.blind_fixture_replay_signals(opponent_team_id);
create index if not exists blind_replay_eval_run_idx on public.blind_fixture_replay_evaluations(run_id,match_id);
create index if not exists blind_replay_evaluations_match_fk_idx on public.blind_fixture_replay_evaluations(match_id);

create or replace view public.current_blind_fixture_replay with (security_invoker=true) as
select m.*,r.replay_version,r.created_at run_created_at,r.input_policy
from public.blind_fixture_replay_matches m join public.blind_fixture_replay_runs r on r.id=m.run_id
where r.id=(select max(id) from public.blind_fixture_replay_runs where gameweek=m.gameweek);

create or replace view public.current_blind_fixture_replay_signals with (security_invoker=true) as
select s.*,r.replay_version,r.created_at run_created_at
from public.blind_fixture_replay_signals s join public.blind_fixture_replay_runs r on r.id=s.run_id
where r.id=(select max(id) from public.blind_fixture_replay_runs where gameweek=s.gameweek);

revoke all on public.current_blind_fixture_replay,public.current_blind_fixture_replay_signals from anon,authenticated;
grant select on public.current_blind_fixture_replay,public.current_blind_fixture_replay_signals to service_role;
