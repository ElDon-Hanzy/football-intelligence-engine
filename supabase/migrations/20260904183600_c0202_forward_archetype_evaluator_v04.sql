  total_points integer,
  goals integer,
  assists integer,
  bonus integer,
  defensive_contribution integer,
  xg numeric,
  xa numeric,
  xgi numeric,
  xgi90 numeric,
  fixture_count integer not null,
  actuals_observed_at timestamptz not null,
  actuals_final boolean not null check (actuals_final),
