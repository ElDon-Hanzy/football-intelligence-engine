with cutoff as (select '2026-09-04T17:30:00Z'::timestamptz ts),
sp as (select * from private.c0202_current_side_prior_v01()),
role_pre as (
  select distinct on (match_id,player_id)
    id,match_id,gameweek,team_id,opponent_team_id,player_id,kickoff_time,captured_at,primary_role,secondary_role,expected_xi,availability_status,confidence,evidence
  from public.player_fixture_role_observations,cutoff
  where gameweek=3 and captured_at<=cutoff.ts
  order by match_id,player_id,captured_at desc,id desc
),
matchup_pre as (
  select distinct on (match_id,team_id,signal_key)
    id,match_id,gameweek,team_id,opponent_team_id,captured_at,signal_key,score,direction,confidence,evidence
  from public.fixture_tactical_matchup_observations,cutoff
  where gameweek=3 and captured_at<=cutoff.ts and signal_key in ('wide_channel_pressure','personnel_disruption')
  order by match_id,team_id,signal_key,captured_at desc,id desc
),
atk as (
 select r.*,p.web_name,sp.inferred_attack_side,sp.confidence_band,sp.empirical_holdout_accuracy
 from role_pre r join public.players p on p.id=r.player_id join sp on sp.player_id=r.player_id
 where r.expected_xi=true and r.availability_status='AVAILABLE'
   and r.primary_role in ('WIDE_ATTACKER','WIDE_FORWARD','WING_BACK','WIDE_BACK')
   and sp.inferred_attack_side in ('ATT_LEFT','ATT_RIGHT')
),
defc as (
 select r.*,p.web_name,sp.inferred_attack_side,sp.confidence_band,sp.empirical_holdout_accuracy
 from role_pre r join public.players p on p.id=r.player_id join sp on sp.player_id=r.player_id
 where r.expected_xi=true and r.availability_status='AVAILABLE'
   and r.primary_role in ('WIDE_BACK','WING_BACK')
   and sp.inferred_attack_side in ('ATT_LEFT','ATT_RIGHT')
),
pairs as (
 select a.*,
   d.id defender_role_observation_id,d.player_id expected_defender_player_id,d.primary_role expected_defender_role,d.captured_at defender_role_captured_at,
   d.confidence defender_role_confidence,d.confidence_band defender_side_confidence_band,d.empirical_holdout_accuracy defender_side_empirical_accuracy,
   row_number() over(partition by a.match_id,a.player_id order by case d.confidence_band when 'HIGH' then 2 when 'MEDIUM' then 1 else 0 end desc,d.confidence desc nulls last,d.player_id) rn
 from atk a
 left join defc d on d.match_id=a.match_id and d.team_id=a.opponent_team_id
   and d.inferred_attack_side=case when a.inferred_attack_side='ATT_LEFT' then 'ATT_RIGHT' else 'ATT_LEFT' end
),
final as (
 select p.*,
   w.id wide_obs_id,w.score wide_score,w.direction wide_direction,w.confidence wide_confidence,w.captured_at wide_captured_at,
   per.id personnel_obs_id,per.score personnel_score,per.direction personnel_direction,per.confidence personnel_confidence,per.captured_at personnel_captured_at
 from pairs p
 left join matchup_pre w on w.match_id=p.match_id and w.team_id=p.team_id and w.signal_key='wide_channel_pressure'
 left join matchup_pre per on per.match_id=p.match_id and per.team_id=p.opponent_team_id and per.signal_key='personnel_disruption'
 where p.rn=1
)
